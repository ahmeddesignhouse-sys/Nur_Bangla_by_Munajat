                        painter = painterResource(id = R.drawable.img_islamic_hero),
                        contentDescription = "ইসলামিক মসজিদ স্থাপত্য",
                        modifier = Modifier.fillMaxSize(),
                        contentScale = ContentScale.Crop
                    )
                    Box(
                        modifier = Modifier
                            .fillMaxSize()
                            .background(
                                Brush.verticalGradient(
                                    colors = listOf(
                                        Color.Transparent,
